const slug = (value: string) => value.toLowerCase().replace(/[^a-z0-9]+/g, "-");

export const defaultSalonServices = rows.map(([salon, category, rawName, minPrice, maxPrice, idOverride], sortOrder) => {
  const priceType: SalonPriceType = /\s*\(mulai dari\)$/i.test(rawName)
    ? "starting"
    : maxPrice !== undefined && maxPrice > minPrice
      ? "range"
      : "fixed";
  const serviceSlug = slug(`${category}-${rawName}`);
  return {
    salon,
    id: idOverride ?? (salon === "hair-studio" ? `hair-studio-${serviceSlug}` : serviceSlug),
    name: rawName.replace(/\s*\(mulai dari\)$/i, ""),
    category,
    sortOrder,
    minPrice,
    maxPrice: priceType === "range" ? maxPrice : null,
    priceType,
    commissionPercent: null,
  };
});
